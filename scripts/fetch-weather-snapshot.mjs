// Bakes a 7-day forecast for every weather point into the bundle, so the app
// shows a real (clearly dated) forecast even on a FIRST load with no signal —
// before any live fetch has ever populated the device cache.
//
// Run: node scripts/fetch-weather-snapshot.mjs

import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const src = await readFile(`${root}/src/data/weatherPoints.ts`, 'utf8');

const points = [...src.matchAll(/id: '([^']+)'[^}]*?lat: ([\d.-]+), lng: ([\d.-]+), ele: (\d+)/g)]
  .map((m) => ({ id: m[1], lat: +m[2], lng: +m[3], ele: +m[4] }));
if (!points.length) throw new Error('no weather points parsed');

const lat = points.map((p) => p.lat).join(',');
const lng = points.map((p) => p.lng).join(',');
const elev = points.map((p) => p.ele).join(',');

const url =
  `https://api.open-meteo.com/v1/forecast?latitude=${lat}&longitude=${lng}&elevation=${elev}` +
  `&current=temperature_2m,weather_code,wind_speed_10m,relative_humidity_2m` +
  `&daily=weather_code,temperature_2m_max,temperature_2m_min,precipitation_sum,precipitation_probability_max,wind_speed_10m_max` +
  `&timezone=auto&forecast_days=7`;

const res = await fetch(url);
if (!res.ok) throw new Error(`Open-Meteo HTTP ${res.status}`);
const json = await res.json();
const arr = Array.isArray(json) ? json : [json];

const norm = (d) => ({
  current: d?.current
    ? {
        temperature: d.current.temperature_2m,
        code: d.current.weather_code,
        wind: d.current.wind_speed_10m,
        humidity: d.current.relative_humidity_2m,
      }
    : null,
  daily: (d?.daily?.time ?? []).map((t, i) => ({
    date: t,
    code: d.daily.weather_code[i],
    tmax: d.daily.temperature_2m_max[i],
    tmin: d.daily.temperature_2m_min[i],
    precip: d.daily.precipitation_sum[i],
    precipProb: d.daily.precipitation_probability_max?.[i] ?? null,
    windMax: d.daily.wind_speed_10m_max?.[i] ?? null,
  })),
});

const out = {};
points.forEach((p, i) => { out[p.id] = norm(arr[i]); });

const file = `// AUTO-GENERATED by scripts/fetch-weather-snapshot.mjs — do not edit by hand.
// A real 7-day forecast baked in at build time, used ONLY as a last-resort
// fallback when the device has no live fetch and no cached forecast. Always
// shown with its capture date so it is never mistaken for current.

import type { PointWeather } from '../hooks/useWeather';

export const SNAPSHOT_AT = ${JSON.stringify(new Date().toISOString())};
export const weatherSnapshot: Record<string, PointWeather> = ${JSON.stringify(out, null, 1)};
`;
await writeFile(`${root}/src/data/weatherSnapshot.generated.ts`, file, 'utf8');
console.log(`snapshot written: ${points.length} points, ${(file.length / 1024).toFixed(1)} KB`);
